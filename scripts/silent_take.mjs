#!/usr/bin/env node
// The "take" of a film with no voice (BRIEF.md `voice: none`): the on-screen text is the script, and a beat's timing is its
// READING time. Each word shows for 0.3 s; a {beat} lasts max(2, 0.3 s a word + 1.2) s (its words, then a hold); words outside
// any beat play on the same clock. Writes what tts_timestamps.mjs writes after a take — audio/beats.json, words.json, beats.js
// (NARRATION_DURATION included) — and a silent audio/narration.wav of that length, so pad_voice, captions and the build run as
// for a voiced film. It always rewrites them from narration.txt (unpadded); pad_voice runs again after it.
//
// Usage: node silent_take.mjs [project]
// Exit 0 written; 1 a missing or unreadable file, a bad narration.txt, or ffmpeg failed.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { parseNarration } from './tts_timestamps.mjs';

const dir = path.resolve(process.argv[2] ?? '.'), A = path.join(dir, 'audio');
const die = m => { console.error(`FAILED: ${m}`); process.exit(1); };
const WORD_S = 0.3, MIN_BEAT_S = 2, HOLD_S = 1.2;
const round = x => Math.round(x * 1000) / 1000;
const strip = w => w.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '');   // as engine/three/type.js and tts_timestamps.mjs

let raw;
try { raw = readFileSync(path.join(dir, 'narration.txt'), 'utf8'); } catch (e) { die(`narration.txt: cannot read (${e.code ?? e.message}) — rerun`); }
const { clean, beats, sections } = parseNarration(raw, false, m => die(`narration.txt: ${m}`));

// the words, as captions' phrases() counts them: [tags] are blanked, a token with no letter or digit is not a word
const blanked = clean.replace(/\[[^\]]*\]/g, s => ' '.repeat(s.length));
const words = [];
for (const m of blanked.matchAll(/\S+/g)) if (/[\p{L}\p{N}]/u.test(m[0])) words.push({ i: words.length, text: strip(m[0]), _s: m.index });

// the reading clock
let t = 0;
const place = w => { w.start = round(t); t += WORD_S; w.end = round(t); };
const used = new Set();
const beatList = beats.map((b, n) => {
  const inside = words.filter(w => w._s >= b.cs && w._s < b.ce);
  let name = b.label || `b${n + 1}`;
  if (!/^[A-Za-z_$][\w$]*$/.test(name)) name = `b${n + 1}`;
  while (used.has(name)) name = `${name}_${n + 1}`;
  used.add(name);
  return { b, name, inside, n };
});
// walk in text order: words outside a beat, then each beat with its hold
let nextBeat = 0;
for (let k = 0; k < words.length || nextBeat < beatList.length;) {
  const bl = beatList[nextBeat];
  const w = words[k];
  if (bl && (!w || bl.b.cs <= w._s) && (bl.inside.length === 0 || bl.inside[0] === w)) {
    const t0 = t;
    bl.inside.forEach(x => { place(x); k++; });
    if (!bl.inside.length) { bl.empty = round(t); }
    t = Math.max(t, t0 + Math.max(MIN_BEAT_S, WORD_S * bl.inside.length + HOLD_S));
    nextBeat++;
  } else if (w) { place(w); k++; } else break;
}
const duration = round(t);

const beatOut = beatList.map(({ b, name, inside, empty }) => ({
  name, text: b.text.trim(),
  start: inside.length ? inside[0].start : empty, end: inside.length ? inside.at(-1).end : empty,
  ...(inside.length && { word_index: inside[0].i }),
}));
const sectionOut = sections.map(s => { const w = words.find(x => x._s >= s.cleanIndex); return { title: s.title, start: w ? w.start : null }; });
const pub = words.map(({ i, text, start, end }) => ({ i, text, start, end }));
const byName = Object.fromEntries(beatOut.map(b => [b.name, { text: b.text, start: b.start, end: b.end }]));

try {
  mkdirSync(A, { recursive: true });
  const ff = spawnSync('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=mono', '-t', String(duration), path.join(A, 'narration.wav')], { encoding: 'utf8' });
  if (ff.status !== 0) die(`ffmpeg: ${(ff.stderr || ff.error?.code || '').trim().split('\n').pop()}`);
  writeFileSync(path.join(A, 'words.json'), JSON.stringify(pub, null, 2));
  writeFileSync(path.join(A, 'beats.json'), JSON.stringify({ duration, audio_file: 'narration.wav', silent: true, beats: beatOut, sections: sectionOut }, null, 2));
  writeFileSync(path.join(A, 'beats.js'),
    `// Generated by silent_take.mjs (voice: none, timed by reading time) — do not edit by hand.\n` +
    `// Use: BEATS.<name>.start (seconds). Ordered list: BEATS_LIST. Sections: SECTIONS.\n` +
    `window.BEATS = ${JSON.stringify(byName, null, 2)};\n` +
    `window.BEATS_LIST = ${JSON.stringify(beatOut)};\n` +
    `window.SECTIONS = ${JSON.stringify(sectionOut)};\n` +
    `// Every word, for changes on words that are not beats: WORDS[i].start (i from words.json).\n` +
    `window.WORDS = ${JSON.stringify(pub.map(({ text, start, end }) => ({ text, start, end })))};\n` +
    `window.NARRATION_DURATION = ${duration};\n`);
} catch (e) { die(`${e.code ?? e.message} — rerun`); }
console.log(`silent take: ${beatOut.length} beats, ${words.length} words, ${duration} s (reading time, no voice): audio/beats.json, words.json, beats.js, narration.wav`);

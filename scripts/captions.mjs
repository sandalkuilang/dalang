#!/usr/bin/env node
// Caption phrases for a film: narration.txt (punctuation) + words.json (timing) -> audio/captions.json and
// audio/captions.js (`window.CAPTIONS = [...]`, loaded like beats.js). The split rules live in engine/three/type.js
// (phrases): sentence ends, `,` `:` after 3 words, at most 7 words (16 characters for CJK), held through the pause.
// Rerun after every take: a narration from another take than words.json is refused.
//
// Usage: node captions.mjs <narration.txt> <words.json> [--out <dir>] [--format shorts|reels|feed|landscape]
// Exit 2 on a usage error, 1 when a file cannot be read or the narration is not the take's.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { phrases } from '../engine/three/type.js';

const usage = 'Usage: node captions.mjs <narration.txt> <words.json> [--out <dir>] [--format shorts|reels|feed|landscape]';
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) { console.log(usage); process.exit(0); }
const flag = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv.splice(i, 2)[1] : undefined; };
const outArg = flag('--out'), format = flag('--format') ?? 'shorts';
const [narrationFile, wordsFile] = argv;
if (!narrationFile || !wordsFile || argv.length !== 2 || !['shorts', 'reels', 'feed', 'landscape'].includes(format) || argv.some(a => a.startsWith('--'))) { console.error(usage); process.exit(2); }

let caps;
try {
  const words = JSON.parse(readFileSync(wordsFile, 'utf8'));
  caps = phrases(readFileSync(narrationFile, 'utf8'), Array.isArray(words) ? words : words.words);
  const out = outArg ?? path.dirname(wordsFile);
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'captions.json'), JSON.stringify({ format, phrases: caps }, null, 2) + '\n');
  writeFileSync(path.join(out, 'captions.js'), `// Generated by captions.mjs — do not edit by hand.\nwindow.CAPTIONS = ${JSON.stringify(caps)};\n`);
  for (const p of caps.slice(0, 40)) console.log(`${p.start.toFixed(2)}–${p.end.toFixed(2)}  ${p.text}`);
  if (caps.length > 40) console.log(`… ${caps.length - 40} more`);
  console.log(`DONE ${path.join(out, 'captions.js')}`);
} catch (e) { console.error(e.message); process.exit(1); }

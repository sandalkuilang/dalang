#!/usr/bin/env node
// Room around the voice: the film opens on its first picture before anyone speaks and holds its last one after. Writes
// audio/voice.wav (the take with `lead` = 1.45 s of silence before and `tail` = 1.35 s after, fixed by SKILL.md) and
// moves every time the take's files hold by `lead`: words.json, beats.json (+ duration, audio_file, a `pad` record),
// beats.js, narration.srt and, when they exist, captions.json and captions.js. The take itself (the file beats.json
// names) is never touched, so a retake still works on it; a retake rewrites the timing files unpadded, and this is run
// again after it.
//
// Usage: node pad_voice.mjs [project]
// Exit 0 padded (or already padded: beats.json has its `pad` record); 1 a missing or unreadable file.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import vm from 'node:vm';

const args = process.argv.slice(2);
const lead = 1.45, tail = 1.35;
const dir = path.resolve(args[0] ?? '.'), A = path.join(dir, 'audio');
const die = m => { console.error(`FAILED: ${m}`); process.exit(1); };
const read = f => { try { return readFileSync(path.join(A, f), 'utf8'); } catch { return null; } };
const r3 = x => Math.round(x * 1000) / 1000;
// every numeric start / end at any depth, moved by lead
const shift = v => Array.isArray(v) ? v.map(shift) : v && typeof v === 'object'
  ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, (k === 'start' || k === 'end') && typeof x === 'number' ? r3(x + lead) : shift(x)])) : v;

const beatsRaw = read('beats.json'), wordsRaw = read('words.json');
if (!beatsRaw || !wordsRaw) die(`${A}/beats.json and words.json are needed (run tts_timestamps.mjs first)`);
const B = JSON.parse(beatsRaw), W = JSON.parse(wordsRaw);
if (B.pad) { console.log(`already padded (lead ${B.pad.lead} s, tail ${B.pad.tail} s): nothing to do; a new take or retake resets it`); process.exit(0); }
const take = path.join(A, B.audio_file ?? 'narration.wav');
if (!existsSync(take)) die(`${take} (beats.json audio_file) is missing`);

const out = path.join(A, 'voice.wav');
const ff = spawnSync('ffmpeg', ['-y', '-v', 'error', '-i', take, '-af', `adelay=${Math.round(lead * 1000)}:all=1,apad=pad_dur=${tail}`, out], { encoding: 'utf8' });
if (ff.status !== 0) die(`ffmpeg: ${(ff.stderr || ff.error?.code || '').trim().split('\n').pop()}`);
const duration = r3((B.duration ?? 0) + lead + tail);

const B2 = { ...shift(B), duration, audio_file: 'voice.wav', pad: { lead, tail, take: B.audio_file ?? 'narration.wav' } };
writeFileSync(path.join(A, 'beats.json'), JSON.stringify(B2, null, 2));
writeFileSync(path.join(A, 'words.json'), JSON.stringify(shift(W), null, 2));

const js = read('beats.js');
if (js) {
  const win = {}; vm.runInNewContext(js, { window: win });
  const keys = Object.keys(win);
  const body = keys.map(k => `window.${k} = ${k === 'NARRATION_DURATION' ? duration : JSON.stringify(shift(win[k]), null, k === 'BEATS' ? 2 : 0)};`).join('\n');
  writeFileSync(path.join(A, 'beats.js'), `// Generated by tts_timestamps.mjs, padded by pad_voice.mjs (lead ${lead} s, tail ${tail} s) — do not edit by hand.\n${body}\n`);
}
const srt = read('narration.srt');
if (srt) writeFileSync(path.join(A, 'narration.srt'), srt.replace(/(\d\d):(\d\d):(\d\d),(\d\d\d)/g, (_, h, m, s, ms) => {
  const t = Math.round(((+h * 60 + +m) * 60 + +s + +ms / 1000 + lead) * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(t / 3600000))}:${p(Math.floor(t / 60000) % 60)}:${p(Math.floor(t / 1000) % 60)},${p(t % 1000, 3)}`;
}));
const cj = read('captions.json');
if (cj) writeFileSync(path.join(A, 'captions.json'), JSON.stringify(shift(JSON.parse(cj)), null, 2));
const cjs = read('captions.js');
if (cjs) { const win = {}; vm.runInNewContext(cjs, { window: win }); writeFileSync(path.join(A, 'captions.js'), `// padded by pad_voice.mjs (lead ${lead} s)\nwindow.CAPTIONS = ${JSON.stringify(shift(win.CAPTIONS))};\n`); }
console.log(`padded: audio/voice.wav = ${lead} s + take + ${tail} s (${duration} s); words, beats, srt${cj || cjs ? ', captions' : ''} moved by ${lead} s`);
